// Fails when a requirement marked "Test" in docs/compliance/requirements.md has no test whose
// title starts with its ID, or when a test names an ID that is not a requirement.
// With --matrix it prints the traceability matrix (docs/compliance/traceability-matrix.md).
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const doc = readFileSync(join(root, "docs/compliance/requirements.md"), "utf8");
const rows = [...doc.matchAll(/^\| (REQ-[A-Z0-9]+-\d+) \|.*\| (Test|Review) \|$/gm)];
const required = new Map(rows.map(([, id, how]) => [id, how]));

function files(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return name === "node_modules" ? [] : files(path);
    return /\.(test|spec)\.ts$/.test(name) ? [path] : [];
  });
}

const evidence = new Map();
for (const file of [...files(join(root, "src")), ...files(join(root, "e2e"))]) {
  for (const [, id, title] of readFileSync(file, "utf8").matchAll(/(?:test|describe)\(\s*"(REQ-[A-Z0-9]+-\d+) ([^"]+)"/g)) {
    if (!evidence.has(id)) evidence.set(id, []);
    evidence.get(id).push(`\`${file.slice(root.length)}\` — ${title}`);
  }
}
const covered = new Set(evidence.keys());

if (process.argv.includes("--matrix")) {
  const titles = new Map([...doc.matchAll(/^\| (REQ-[A-Z0-9]+-\d+) \| (.+?) \| ([HML]) \| (Test|Review) \|$/gm)].map((m) => [m[1], m]));
  console.log("# Traceability matrix\n");
  console.log("Generated by `node scripts/check-traceability.mjs --matrix`; do not edit by hand.\n");
  console.log("| ID | Risk | Requirement | Verification evidence |\n| --- | --- | --- | --- |");
  for (const [id, how] of required) {
    const [, , text, risk] = titles.get(id);
    const proof = how === "Review" ? "Code review in the pull request (see change-control.md)" : (evidence.get(id) ?? []).join("<br>");
    console.log(`| ${id} | ${risk} | ${text} | ${proof} |`);
  }
  process.exit(0);
}

const missing = [...required].filter(([id, how]) => how === "Test" && !covered.has(id)).map(([id]) => id);
const unknown = [...covered].filter((id) => !required.has(id));

for (const id of missing) console.error(`No test for ${id}`);
for (const id of unknown) console.error(`Test names unknown requirement ${id}`);
if (missing.length || unknown.length) process.exit(1);
console.log(`Traceability OK: ${required.size} requirements, ${covered.size} covered by tests.`);
